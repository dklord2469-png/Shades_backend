CREATE DATABASE IF NOT EXISTS ECOMMERCE_DB;

USE ECOMMERCE_DB;


-- =========================================================
-- USERS AND ACCESS CONTROL
-- =========================================================

CREATE TABLE USERS (
    USER_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    EMAIL VARCHAR(255) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    PHONE_NUMBER VARCHAR(20),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);


CREATE TABLE ROLES (
    ROLE_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    ROLE_NAME VARCHAR(50) NOT NULL,
    DESCRIPTION VARCHAR(255),

    CONSTRAINT UQ_ROLE_NAME UNIQUE (ROLE_NAME)
);


CREATE TABLE USER_ROLES (
    USER_ID BIGINT NOT NULL,
    ROLE_ID BIGINT NOT NULL,
    ASSIGNED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (USER_ID, ROLE_ID),

    CONSTRAINT FK_USER_ROLE_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_USER_ROLE_ROLE
        FOREIGN KEY (ROLE_ID)
        REFERENCES ROLES(ROLE_ID)
        ON DELETE CASCADE
);


CREATE TABLE ADDRESSES (
    ADDRESS_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    USER_ID BIGINT NOT NULL,
    ADDRESS_TYPE VARCHAR(20) DEFAULT 'SHIPPING',
    RECIPIENT_NAME VARCHAR(255) NOT NULL,
    PHONE_NUMBER VARCHAR(20),
    HOUSE_NUMBER VARCHAR(50),
    ADDRESS_LINE_1 VARCHAR(255) NOT NULL,
    ADDRESS_LINE_2 VARCHAR(255),
    CITY VARCHAR(100) NOT NULL,
    STATE VARCHAR(100) NOT NULL,
    PINCODE VARCHAR(20) NOT NULL,
    COUNTRY VARCHAR(100) NOT NULL,
    IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_ADDRESS_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT CHK_ADDRESS_TYPE
        CHECK (ADDRESS_TYPE IN ('SHIPPING', 'BILLING', 'BOTH'))
);

CREATE INDEX IDX_ADDRESSES_USER_ID
    ON ADDRESSES(USER_ID);


-- =========================================================
-- TAX AND PRODUCT CATALOG
-- =========================================================

CREATE TABLE TAX_RATES (
    TAX_RATE_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    TAX_NAME VARCHAR(100) NOT NULL,
    COUNTRY VARCHAR(100),
    STATE VARCHAR(100),
    RATE_PERCENT DECIMAL(7, 4) NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    VALID_FROM DATETIME,
    VALID_TO DATETIME,

    CONSTRAINT CHK_TAX_RATE
        CHECK (RATE_PERCENT >= 0)
);


CREATE TABLE PRODUCTS (
    PRODUCT_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    TAX_RATE_ID BIGINT,
    PRODUCT_NAME VARCHAR(255) NOT NULL,
    PRODUCT_DESCRIPTION TEXT,
    BRAND VARCHAR(150),
    BASE_PRICE DECIMAL(12, 2) NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT FK_PRODUCT_TAX_RATE
        FOREIGN KEY (TAX_RATE_ID)
        REFERENCES TAX_RATES(TAX_RATE_ID)
        ON DELETE SET NULL,

    CONSTRAINT CHK_PRODUCT_PRICE
        CHECK (BASE_PRICE >= 0)
);

CREATE INDEX IDX_PRODUCTS_NAME
    ON PRODUCTS(PRODUCT_NAME);

CREATE INDEX IDX_PRODUCTS_BRAND
    ON PRODUCTS(BRAND);


CREATE TABLE CATEGORIES (
