CREATE TABLE PRODUCT_VARIANTS (
    VARIANT_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PRODUCT_ID BIGINT NOT NULL,
    SKU VARCHAR(100) NOT NULL,
    VARIANT_NAME VARCHAR(255),
    VARIANT_DESCRIPTION TEXT,
    PRICE DECIMAL(12, 2) NOT NULL,
