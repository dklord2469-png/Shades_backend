-- =========================================================
-- COUPONS
-- =========================================================

CREATE TABLE COUPONS (
    COUPON_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    COUPON_CODE VARCHAR(50) NOT NULL,
    DESCRIPTION VARCHAR(255),
    DISCOUNT_TYPE VARCHAR(20) NOT NULL,
    DISCOUNT_VALUE DECIMAL(12, 2) NOT NULL,
    MINIMUM_ORDER_AMOUNT DECIMAL(12, 2) NOT NULL DEFAULT 0,
    MAXIMUM_DISCOUNT_AMOUNT DECIMAL(12, 2),
    USAGE_LIMIT INT,
    USAGE_LIMIT_PER_USER INT,
    VALID_FROM DATETIME NOT NULL,
    VALID_TO DATETIME NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT UQ_COUPON_CODE UNIQUE (COUPON_CODE),

    CONSTRAINT CHK_COUPON_TYPE
        CHECK (DISCOUNT_TYPE IN ('PERCENTAGE', 'FIXED', 'PAIR_FIXED')),

    CONSTRAINT CHK_COUPON_VALUE
        CHECK (DISCOUNT_VALUE > 0),

    CONSTRAINT CHK_COUPON_MINIMUM_AMOUNT
        CHECK (MINIMUM_ORDER_AMOUNT >= 0),

    CONSTRAINT CHK_COUPON_DATES
        CHECK (VALID_TO > VALID_FROM)
);


-- =========================================================
-- ORDERS
-- =========================================================

CREATE TABLE ORDERS (
    ORDER_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    USER_ID BIGINT NOT NULL,
    SHIPPING_ADDRESS_ID BIGINT,
    BILLING_ADDRESS_ID BIGINT,
    COUPON_ID BIGINT,
    ORDER_STATUS VARCHAR(30) NOT NULL DEFAULT 'PLACED',
    SUBTOTAL_AMOUNT DECIMAL(12, 2) NOT NULL,
    DISCOUNT_AMOUNT DECIMAL(12, 2) NOT NULL DEFAULT 0,
    TAX_AMOUNT DECIMAL(12, 2) NOT NULL DEFAULT 0,
    SHIPPING_AMOUNT DECIMAL(12, 2) NOT NULL DEFAULT 0,
    TOTAL_AMOUNT DECIMAL(12, 2) NOT NULL,

    SHIPPING_NAME VARCHAR(255) NOT NULL,
    SHIPPING_PHONE VARCHAR(20),
    SHIPPING_ADDRESS_LINE_1 VARCHAR(255) NOT NULL,
    SHIPPING_ADDRESS_LINE_2 VARCHAR(255),
    SHIPPING_CITY VARCHAR(100) NOT NULL,
    SHIPPING_STATE VARCHAR(100) NOT NULL,
    SHIPPING_PINCODE VARCHAR(20) NOT NULL,
    SHIPPING_COUNTRY VARCHAR(100) NOT NULL,

    PURCHASED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DELIVERED_AT DATETIME,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT FK_ORDER_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_ORDER_SHIPPING_ADDRESS
        FOREIGN KEY (SHIPPING_ADDRESS_ID)
        REFERENCES ADDRESSES(ADDRESS_ID)
        ON DELETE SET NULL,

    CONSTRAINT FK_ORDER_BILLING_ADDRESS
        FOREIGN KEY (BILLING_ADDRESS_ID)
        REFERENCES ADDRESSES(ADDRESS_ID)
        ON DELETE SET NULL,

    CONSTRAINT FK_ORDER_COUPON
        FOREIGN KEY (COUPON_ID)
        REFERENCES COUPONS(COUPON_ID)
        ON DELETE SET NULL,

    CONSTRAINT CHK_ORDER_STATUS
        CHECK (
            ORDER_STATUS IN (
                'PLACED',
                'CONFIRMED',
                'PROCESSING',
                'SHIPPED',
                'DELIVERED',
                'CANCELLED',
                'RETURNED'
            )
        ),

    CONSTRAINT CHK_ORDER_AMOUNTS
        CHECK (
            SUBTOTAL_AMOUNT >= 0
            AND DISCOUNT_AMOUNT >= 0
            AND TAX_AMOUNT >= 0
            AND SHIPPING_AMOUNT >= 0
            AND TOTAL_AMOUNT >= 0
        )
);

CREATE INDEX IDX_ORDERS_USER
    ON ORDERS(USER_ID);

CREATE INDEX IDX_ORDERS_STATUS
    ON ORDERS(ORDER_STATUS);

CREATE INDEX IDX_ORDERS_PURCHASED_AT
    ON ORDERS(PURCHASED_AT);


CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    ORDER_ID BIGINT NOT NULL,
    VARIANT_ID BIGINT NOT NULL,
    PRODUCT_NAME VARCHAR(255) NOT NULL,
    SKU VARCHAR(100) NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE DECIMAL(12, 2) NOT NULL,
    TAX_AMOUNT DECIMAL(12, 2) NOT NULL DEFAULT 0,
    DISCOUNT_AMOUNT DECIMAL(12, 2) NOT NULL DEFAULT 0,
    LINE_TOTAL DECIMAL(12, 2) NOT NULL,

    CONSTRAINT UQ_ORDER_VARIANT
        UNIQUE (ORDER_ID, VARIANT_ID),

    CONSTRAINT FK_ORDER_ITEM_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_ORDER_ITEM_VARIANT
        FOREIGN KEY (VARIANT_ID)
        REFERENCES PRODUCT_VARIANTS(VARIANT_ID),

    CONSTRAINT CHK_ORDER_ITEM_QUANTITY
        CHECK (QUANTITY > 0),

    CONSTRAINT CHK_ORDER_ITEM_AMOUNTS
        CHECK (
            UNIT_PRICE >= 0
            AND TAX_AMOUNT >= 0
            AND DISCOUNT_AMOUNT >= 0
            AND LINE_TOTAL >= 0
        )
);

CREATE INDEX IDX_ORDER_ITEMS_ORDER
    ON ORDER_ITEMS(ORDER_ID);

CREATE INDEX IDX_ORDER_ITEMS_VARIANT
    ON ORDER_ITEMS(VARIANT_ID);


