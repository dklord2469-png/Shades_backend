        FOREIGN KEY (PRODUCT_ID)
        REFERENCES PRODUCTS(PRODUCT_ID)
        ON DELETE CASCADE,

    CONSTRAINT CHK_VARIANT_PRICE
        CHECK (PRICE >= 0),

    CONSTRAINT CHK_VARIANT_QUANTITY
        CHECK (QUANTITY_AVAILABLE >= 0),

    CONSTRAINT CHK_LOW_STOCK_THRESHOLD
        CHECK (LOW_STOCK_THRESHOLD >= 0)
);

CREATE INDEX IDX_PRODUCT_VARIANTS_PRODUCT
    ON PRODUCT_VARIANTS(PRODUCT_ID);


CREATE TABLE PRODUCT_ATTRIBUTES (
    ATTRIBUTE_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PRODUCT_ID BIGINT NOT NULL,
    VARIANT_ID BIGINT,
    ATTRIBUTE_NAME VARCHAR(100) NOT NULL,
    ATTRIBUTE_VALUE VARCHAR(255) NOT NULL,

    CONSTRAINT FK_ATTRIBUTE_PRODUCT
        FOREIGN KEY (PRODUCT_ID)
        REFERENCES PRODUCTS(PRODUCT_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_ATTRIBUTE_VARIANT
        FOREIGN KEY (VARIANT_ID)
        REFERENCES PRODUCT_VARIANTS(VARIANT_ID)
        ON DELETE CASCADE,

    CONSTRAINT UQ_PRODUCT_ATTRIBUTE
        UNIQUE (
            PRODUCT_ID,
            VARIANT_ID,
            ATTRIBUTE_NAME,
            ATTRIBUTE_VALUE
        )
);

CREATE INDEX IDX_PRODUCT_ATTRIBUTES_PRODUCT
    ON PRODUCT_ATTRIBUTES(PRODUCT_ID);

CREATE INDEX IDX_PRODUCT_ATTRIBUTES_VARIANT
    ON PRODUCT_ATTRIBUTES(VARIANT_ID);


CREATE TABLE INVENTORY_MOVEMENTS (
    INVENTORY_MOVEMENT_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    VARIANT_ID BIGINT NOT NULL,
    MOVEMENT_TYPE VARCHAR(30) NOT NULL,
    QUANTITY_CHANGE INT NOT NULL,
    REFERENCE_TYPE VARCHAR(50),
    REFERENCE_ID BIGINT,
    NOTES VARCHAR(500),
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_INVENTORY_VARIANT
        FOREIGN KEY (VARIANT_ID)
        REFERENCES PRODUCT_VARIANTS(VARIANT_ID),

    CONSTRAINT CHK_INVENTORY_MOVEMENT_TYPE
        CHECK (
            MOVEMENT_TYPE IN (
                'PURCHASE',
                'SALE',
                'CANCELLATION',
                'RETURN',
                'ADJUSTMENT'
            )
        ),

    CONSTRAINT CHK_INVENTORY_CHANGE
        CHECK (QUANTITY_CHANGE <> 0)
);

CREATE INDEX IDX_INVENTORY_VARIANT
    ON INVENTORY_MOVEMENTS(VARIANT_ID);

CREATE INDEX IDX_INVENTORY_REFERENCE
    ON INVENTORY_MOVEMENTS(REFERENCE_TYPE, REFERENCE_ID);


